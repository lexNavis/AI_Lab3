import pandas as pd

# Загружаем исходный датасет. В этом файле разделитель — точка с запятой, а не запятая.
df = pd.read_csv('../../data/bank-additional-full.csv', sep=';')

print("=== 1. Размер датасета до обработки ===")
print(f"Строк: {df.shape[0]}, Колонок: {df.shape[1]}")

print("\n=== 2. Проверка на явные пропуски (NaN) ===")
# Считаем количество пустых ячеек в каждой колонке. 
# Если суммарное количество пропусков равно нулю, выводим соответствующее сообщение.
missing = df.isnull().sum()
print(missing[missing > 0] if missing.sum() > 0 else "Явных пропусков (NaN) нет.")

print("\n=== 3. Проверка категории 'unknown' ===")
# В данном датасете отсутствие информации часто закодировано строкой 'unknown'.
# Проверяем текстовые колонки на наличие таких значений и считаем их долю.
for col in df.columns:
    if df[col].dtype == 'object':
        unknown_count = (df[col] == 'unknown').sum()
        if unknown_count > 0:
            percent = (unknown_count / len(df)) * 100
            print(f"Колонка '{col}': {unknown_count} значений 'unknown' ({percent:.2f}%)")

print("\n=== 4. Проверка на полные дубликаты строк ===")
# Ищем строки, которые полностью повторяют друг друга по всем признакам.
duplicates = df.duplicated().sum()
print(f"Полных дубликатов строк: {duplicates}")

print("\n=== 5. Анализ признака pdays ===")
# Значение 999 в pdays — это специальный маркер, означающий, что клиента ранее не беспокоили.
# Считаем количество таких записей для дальнейшей обработки этого признака.
pdays_999 = (df['pdays'] == 999).sum()
print(f"Записей с pdays = 999: {pdays_999} (клиент ранее не был проинформирован)")

print("\n=== 6. Распределение целевой переменной ===")
# Оцениваем дисбаланс классов. Это важно, так как при сильном перекосе 
# стандартная метрика Accuracy будет неинформативной.
print(df['y'].value_counts())
print(f"Доля откликов 'yes': {(df['y'] == 'yes').mean() * 100:.2f}%")